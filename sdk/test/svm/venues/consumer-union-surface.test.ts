describe('consumer-union barrel surface (sauce-recipes)', () => {
  it('pins the expected counts (346 values, 83 types) so a future edit is deliberate', () => {
    expect(CONSUMER_UNION_VALUES.length).toBe(346);
    expect(CONSUMER_UNION_TYPES.length).toBe(83);
  });

  it('every consumer-union VALUE resolves through the built @eco-incorp/sauce-sdk/svm barrel', () => {
    const missing = CONSUMER_UNION_VALUES.filter((name) => (svm as Record<string, unknown>)[name] === undefined);
    expect(missing).toEqual([]);
  });

  it('every consumer-union TYPE resolves -- checked via the TypeScript compiler API against the fixture', () => {
    const fixturePath = join(HERE, 'consumer-union-types.fixture.ts');
    const program = ts.createProgram([fixturePath], {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ESNext,
      moduleResolution: ts.ModuleResolutionKind.Bundler,
      strict: true,
      esModuleInterop: true,
      skipLibCheck: true,
      noEmit: true,
    });
    const diagnostics = ts
      .getPreEmitDiagnostics(program)
      .filter((d) => d.file?.fileName === fixturePath)
      .map((d) => ts.flattenDiagnosticMessageText(d.messageText, '\n'));
    expect(diagnostics).toEqual([]);
  });

  it('sanity: every CONSUMER_UNION_TYPES name is absent from CONSUMER_UNION_VALUES (no double-classification)', () => {
    const valueSet = new Set(CONSUMER_UNION_VALUES);
    const overlap = CONSUMER_UNION_TYPES.filter((name) => valueSet.has(name));
    expect(overlap).toEqual([]);
  });
});
