/**
 * Consumer-union barrel-surface check -- the omission-catching counterpart to
 * migrated-barrel-surface.test.ts (see that file's header for the full
 * distinction). That sibling test asserts the migration's OWN emitted name
 * list against itself -- it re-derives its 474 names by reading the very
 * `venues/index.ts` lines it is meant to guard, so a name the migration never
 * thought to export at all is invisible to it by construction. This is
 * exactly how `SvmHyloDriftError`'s earlier absence from the barrel survived
 * that test unnoticed.
 *
 * This test instead asserts against an INDEPENDENTLY-SOURCED list: every
 * symbol name the downstream `sauce-recipes` package actually consumes,
 * extracted mechanically from ITS source tree, not from anything in this
 * repo. A name omitted here fails in the SDK, at PR time -- not one repo
 * away, after a re-pin.
 *
 * DERIVATION. In the `sauce-recipes` repo, over `ecoswap/svm/**`,
 * `solswap/**`, and `test/svm/**`: take the union of every named import (a)
 * sourced directly from `'@eco-incorp/sauce-sdk/svm'` today (names already
 * satisfied by pre-existing venues, e.g. `raydium-clmm`, `orca-whirlpool`,
 * `woofi`, `quantum`, `deriverse`, `goonfi-v2` -- all merged to this SDK
 * before this migration and unaffected by it), UNION (b) every named import
 * sourced from one of the 44 LOCAL venue module files THIS migration deletes
 * (`ecoswap/svm/venues/<key>.ts` or `<key>/{index,ladder}.ts`, for each of
 * the 44 keys this PR adds under `sdk/src/svm/venues/`) -- because once the
 * sauce-recipes-side companion re-pin lands, every such import becomes a
 * barrel import instead, and (a) alone would miss every migrated name that
 * isn't imported from the barrel yet. Import sites INSIDE the 44
 * soon-to-be-deleted local files themselves are excluded as sources (they
 * won't exist to import anything once deleted); every other file in the
 * three dirs above -- including the per-venue unit-test files under
 * `test/svm/venues/*.test.ts`, which keep testing the same logic
 * post-migration -- is a real, surviving consumer.
 *
 * 429 names total: 346 VALUES (below) + 83 TYPES
 * (consumer-union-types.fixture.ts). 279 of the 346 values (and all but a
 * handful of the types) are NOT satisfiable by `origin/main` today -- they
 * name one of the 44 newly-migrated venues. Measured directly (two full
 * `pnpm build`s, one per commit, this exact list run against each built
 * `sdk/dist/svm/index.js`): 232 of the 346 values and 45 of the 83 types are
 * UNDEFINED / unresolvable against `origin/main`'s dist (277 total), and 0 of
 * either are unresolvable against this branch's dist (post `SvmHyloDriftError`
 * fix). That gap is the non-vacuity proof for this test: an omission here is
 * not a hypothetical, it is what the barrel looked like one commit ago.
 *
 * VALUES are probed as runtime values against the built module namespace --
 * the exact thing a real `import { X } from '@eco-incorp/sauce-sdk/svm'`
 * needs. TYPES have no runtime presence and this package's `jest.config.cjs`
 * runs ts-jest with `diagnostics: false`, so a bare `import type { Foo }`
 * that names a missing export is SILENTLY ERASED at transpile time and would
 * never fail a jest run by itself -- to make the type half load-bearing, the
 * third test below drives the TypeScript compiler API directly (in-process,
 * not a subprocess) against `consumer-union-types.fixture.ts`, a file whose
 * only job is to import every listed type and reference each in one tuple
 * position, and asserts zero diagnostics.
 */
